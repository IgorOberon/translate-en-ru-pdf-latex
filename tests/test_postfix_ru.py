#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""postfix_ru.py: типографика, ложные списки, швы, терминология и — главное —
правила СО СМЕНОЙ РОДА.

Про род здесь особый счёт. На томе 6 такие правила трижды дали тихую порчу
русского языка, и каждый раз её ловила не сборка, а отдельная проверка. Все
три класса — ниже, вместе со случаями, где правильный ответ «НЕ МЕНЯТЬ»:
именно они и отличают согласованную замену от сделанной наполовину.

  · «логический» -> «логическее» (после заднеязычных средний род на «-ое»);
  · «представляет собой отражение» -> «... собой рефлексия» (винительный);
  · «разумный вывод возможен» -> «разумное умозаключение возможен».

Запуск: python tests/test_postfix_ru.py      (код 1 при провале)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import postfix_ru as P  # noqa: E402

CHECKS = []


def eq(name, got, want):
    CHECKS.append((name, got == want, f"получено «{got}»\n         ждали  «{want}»"))


# формы «вывод» -> «умозаключение» только для прямых падежей: в косвенных
# определение мужского и среднего рода совпадает, там работает обычное правило
SCHLUSS = {"вывод": "умозаключение"}


def m2n(text):
    return P.replace_m2n(text, SCHLUSS, "Schluß→умозаключение")


def test_gender_m2n():
    eq("определение-прилагательное согласовано",
       m2n("разумный вывод"), "разумное умозаключение")
    eq("заднеязычная основа: «-ое», а не «-ее»",
       m2n("логический вывод"), "логическое умозаключение")
    eq("шипящая основа: «-ое»",
       m2n("общий вывод"), "общее умозаключение")
    eq("местоимение согласовано",
       m2n("этот вывод"), "это умозаключение")
    eq("«весь» — исключение",
       m2n("весь вывод"), "всё умозаключение")
    eq("без определения — просто замена",
       m2n("Вывод следует из посылок"), "Умозаключение следует из посылок")
    eq("прописная сохраняется",
       m2n("Этот вывод"), "Это умозаключение")

    # --- НЕ МЕНЯТЬ
    eq("«-ой» неоднозначно (мужское прил. или творительный женского) — не менять",
       m2n("представляет собой вывод"), "представляет собой вывод")
    eq("сказуемое-краткое прилагательное согласовано",
       m2n("разумный вывод возможен"), "разумное умозаключение возможно")
    eq("прошедшее время согласовано",
       m2n("вывод следовал из посылок"),
       "умозаключение следовало из посылок")
    eq("возвратный глагол согласован",
       m2n("вывод заключался в этом"), "умозаключение заключалось в этом")
    eq("незнакомое краткое прилагательное — замену пропускаем целиком",
       m2n("вывод правомерен"), "вывод правомерен")
    eq("сказуемое за точкой к делу не относится",
       m2n("вывод. Он важен"), "умозаключение. Он важен")
    eq("предлог перед словом определением не является",
       m2n("из вывод"), "из умозаключение")


# «отражение» -> «рефлексия»: средний род на женский, по падежам
REFL = [("отражение", "рефлексия", {"ое": "ая", "ее": "яя"}),
        ("отражения", "рефлексии", {"ого": "ой", "его": "ей"}),
        ("отражением", "рефлексией", {"ым": "ой", "им": "ей"})]


def n2f(text):
    return P.replace_n2f(text, REFL, "Reflexion→рефлексия")


def test_gender_n2f():
    eq("без определения — просто замена",
       n2f("здесь отражение сущности"), "здесь рефлексия сущности")
    eq("определение согласовано по падежу",
       n2f("чистое отражение"), "чистая рефлексия")
    eq("родительный падеж, местоимение",
       n2f("этого отражения"), "этой рефлексии")
    eq("родительный падеж, прилагательное (окончание трёхбуквенное)",
       n2f("чистого отражения"), "чистой рефлексии")
    eq("творительный падеж",
       n2f("чистым отражением"), "чистой рефлексией")
    eq("местоимение согласовано",
       n2f("это отражение"), "эта рефлексия")

    # --- НЕ МЕНЯТЬ: винительный среднего совпадает с именительным
    eq("«представляет собой отражение» — винительный, не менять",
       n2f("представляет собой отражение"),
       "представляет собой отражение")
    eq("«находят своё отражение» — винительный при притяжательном",
       n2f("находят своё отражение"), "находят своё отражение")
    eq("«имеет отражение» — винительный при глаголе",
       n2f("имеет отражение"), "имеет отражение")
    eq("«через отражение» — винительный при предлоге",
       n2f("через отражение"), "через отражение")
    eq("определение согласовано и в творительном",
       n2f("многообразным отражением"), "многообразной рефлексией")
    # у этого падежа правил для определения нет вовсе — значит и замены нет
    no_adj = [("отражению", "рефлексии", {})]
    eq("определение есть, а правила для него нет — не менять",
       P.replace_n2f("чистому отражению", no_adj, "x"),
       "чистому отражению")
    eq("без определения тот же падеж меняется",
       P.replace_n2f("благодаря отражению", no_adj, "x"),
       "благодаря рефлексии")
    eq("предложный падеж вне списка — не трогается",
       n2f("в отражении вещи"), "в отражении вещи")


def test_prepositions():
    eq("«об» перед согласной становится «о»",
       P.fix_prepositions("об предмете"), "о предмете")
    eq("«о» перед гласной становится «об»",
       P.fix_prepositions("о объекте"), "об объекте")
    eq("верный предлог не трогается",
       P.fix_prepositions("о предмете и об идее"), "о предмете и об идее")
    eq("устойчивый оборот не трогается",
       P.fix_prepositions("шла рука об руку с науками"),
       "шла рука об руку с науками")
    eq("соприкосновение не трогается",
       P.fix_prepositions("удариться об стену"), "удариться об стену")


def test_typography():
    eq("короткое тире -> длинное с неразрывным пробелом",
       P.fix_typography("слово – другое"), "слово — другое")
    eq("немецкие лапки -> ёлочки",
       P.fix_typography("он сказал „нечто“ вслух"),
       "он сказал «нечто» вслух")
    eq("математический минус не превращается в тире",
       P.fix_typography("значения + и - равны"), "значения + и - равны")
    eq("неразрывный пробел после §",
       P.fix_typography("см. § 86"), "см. § 86")
    eq("чистый текст не трогается",
       P.fix_typography("обычная фраза без затей."),
       "обычная фраза без затей.")


def test_false_lists():
    eq("огрызок рубрики экранируется",
       P.escape_false_lists("y) В процессе размышления"),
       "y\\) В процессе размышления")
    eq("обычный абзац не трогается",
       P.escape_false_lists("Обычный абзац."), "Обычный абзац.")


def test_seam():
    eq("сомнительное многоточие требует проверки, не заменяется вслепую",
       P.fix_seam_ellipsis("Es waere besser. Nicht zu reden.",
                           "Было бы лучше… Не стоит говорить."),
       "Было бы лучше… Не стоит говорить.")
    eq("авторское многоточие остаётся",
       P.fix_seam_ellipsis("Es waere besser… Nicht zu reden.",
                           "Было бы лучше… Не стоит говорить."),
       "Было бы лучше… Не стоит говорить.")


def test_terms():
    rules = P.compile_rules([{
        "name": "Verstand→рассудок",
        "anchor": r"Verstand", "competitor": r"Vernunft",
        "pairs": [["разум", "рассудок"], ["разума", "рассудка"]]}])
    eq("якорь есть, конкурента нет — заменяем",
       P.fix_terms("Der Verstand ist bestimmt.", "Разум определён.", rules),
       "Рассудок определён.")
    eq("конкурент в блоке — не заменяем",
       P.fix_terms("Verstand und Vernunft.", "Разум определён.", rules),
       "Разум определён.")
    eq("якоря нет — не заменяем",
       P.fix_terms("Die Idee ist wahr.", "Разум определён.", rules),
       "Разум определён.")
    eq("длинная форма раньше короткой",
       P.fix_terms("Der Verstand.", "нет разума здесь", rules),
       "нет рассудка здесь")

    par = P.compile_rules([{
        "name": "Gegenstand→предмет", "anchor": r"Gegenstand",
        "from": "объект", "to": "предмет", "paradigm": "noun_m"}])
    eq("парадигма разворачивается в формы",
       P.fix_terms("Der Gegenstand.", "об объекте и объектами", par),
       "об предмете и предметами")
    # предлог чинится следующим шагом конвейера, не самой заменой
    eq("замена + согласование предлога дают верную фразу",
       P.fix_prepositions(
           P.fix_terms("Der Gegenstand.", "об объекте и объектами", par)),
       "о предмете и предметами")


def test_tier_openers():
    eq("зачин яруса выделяется",
       P.mark_tier_openers("Прибавление. Здесь поясняется.", ["Прибавление"]),
       "**Прибавление.** Здесь поясняется.")
    eq("зачин с номером",
       P.mark_tier_openers("Прибавление 2. Далее.", ["Прибавление"]),
       "**Прибавление 2.** Далее.")
    eq("обычный абзац не трогается",
       P.mark_tier_openers("Прибавления бывают разные.", ["Прибавление"]),
       "Прибавления бывают разные.")


def test_footnotes():
    de = ["Er sagt es klar. *) Nicht nur hier.", "*) Anmerkung des Autors."]
    ru = ["Он говорит ясно. *) Не только здесь.", "*) Примечание автора."]
    d2, r2 = P.link_footnotes(de, ru)
    eq("отсылка заменена маркой", "[^fn1]" in r2[0], True)
    eq("определение сноски уехало в конец",
       r2[-1], "[^fn1]: Примечание автора.")


def test_zzz_все_проверки_прошли():
    """Проверки выше копят результат в CHECKS, а не падают на месте: так
    виден ВЕСЬ список расхождений, а не первое. Здесь и стоит тот assert,
    без которого pytest считал бы набор зелёным при любых провалах."""
    fails = ["{}: {}".format(n, x) for n, ok, x in CHECKS if not ok]
    assert not fails, "провалов {}:\n  ".format(len(fails)) + "\n  ".join(
        fails[:10])


def main():
    for t in (test_gender_m2n, test_gender_n2f, test_prepositions,
              test_typography, test_false_lists, test_seam,
              test_terms, test_tier_openers, test_footnotes):
        try:
            t()
        except Exception as e:                          # noqa: BLE001
            CHECKS.append((f"{t.__name__} не упал", False, repr(e)[:200]))
    bad = 0
    for name, ok, extra in CHECKS:
        print(("PASS " if ok else "FAIL ") + name
              + ("" if ok else f"\n      -> {extra}"))
        bad += not ok
    print(f"\n{len(CHECKS) - bad}/{len(CHECKS)} passed")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
